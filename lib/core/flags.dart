/// 빌드 스위치 두 개.
///
/// 둘 다 **한 군데에 모아 둔다** — 화면마다 `kDebugMode`를 직접 보면
/// "디버그에서만 보이는 것"이 어디에 몇 개인지 아무도 모르게 된다.
library;

import 'package:flutter/foundation.dart';

/// **스토어 스크린샷을 찍을 때만** true.
///
/// 광고 배너와 디버그 UI가 통째로 빠진다. 이게 없을 때는 찍을 때마다
/// `kDebugStages`를 손으로 껐다 켜고 광고도 따로 막아야 했고, 그러다
/// **테스트 광고와 ⏩ 버튼이 찍힌 스크린샷**을 만들었다.
///
/// 찍는 절차는 `store/RELEASE.md`의 "스크린샷" 절에 있다.
/// **찍고 나면 반드시 false로 되돌릴 것** — 켠 채로 올리면 광고 수익이 0이다.
const bool kShotMode = false;

/// 디버그 도구(레벨 점프·먹이 채우기·판 즉시 완료).
///
/// 지우지 않고 여기에 묶어 둔다 — 릴리스에서는 false라 트리 셰이킹으로
/// 통째로 빠지고, 디버그 빌드에서는 그대로 쓸 수 있다. 손으로 껐다 켜면
/// 켠 채로 스토어에 올리는 사고가 언젠가 난다.
const bool kDebugStages = kDebugMode && !kShotMode;
